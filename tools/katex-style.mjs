// Writes packages/markdown/src/html/katex-style.ts: KaTeX's stylesheet with
// its fonts in it, as data URLs.
//
// A formula has to look the same on the screen, in the HTML handed to a
// reader, and in the picture a PDF or a slide gets — and the last is drawn
// from an SVG image, which loads nothing from outside itself. So the fonts
// travel inside the CSS. Run again after KaTeX is updated:
//   node tools/katex-style.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';

const require = createRequire(import.meta.url);
const dist = dirname(require.resolve('katex/dist/katex.min.css'));
const { version } = JSON.parse(readFileSync(join(dist, '..', 'package.json'), 'utf8'));
let css = readFileSync(join(dist, 'katex.min.css'), 'utf8');
// Only the WOFF2 of each face: every browser that runs this reads it.
css = css.replace(/src:url\(fonts\/([^)]+?\.woff2)\) format\("woff2"\)(,url\([^)]*\) format\("[^"]*"\))*/g, (_, file) => {
  const data = readFileSync(join(dist, 'fonts', file)).toString('base64');
  return `src:url(data:font/woff2;base64,${data}) format("woff2")`;
});
if (/url\(fonts\//.test(css)) throw new Error('a font was left as a file');
writeFileSync('packages/markdown/src/html/katex-style.ts',
  `// Generated by tools/katex-style.mjs from KaTeX ${version}. Do not edit.\n`
  + `/* eslint-disable */\n`
  + `/** KaTeX's stylesheet, its fonts inside it as data URLs. */\n`
  + `export const KATEX_STYLE = ${JSON.stringify(css)};\n`);
console.log(`katex-style.ts (${Math.round(css.length / 1024)} KB, KaTeX ${version})`);
